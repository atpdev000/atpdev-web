export const getTool = (id: string): ToolDef => {
    const tool = TOOLS.find((t) => t.id === id);
    if (!tool) throw new Error(`Unknown tool: ${id}`);
    return tool;
};

export const readyTools = () => TOOLS.filter((t) => t.status === 'ready');
