export function drawBrandLogoOnCanvas(
  ctx: CanvasRenderingContext2D,
  logoType: QROptionLogo,
  cx: number,
  cy: number,
  size: number
): boolean {
  const spec = BRAND_LOGOS[logoType];
  if (!spec) return false;

  ctx.save();
  const radius = size * 0.45;
  const x = cx - radius;
  const y = cy - radius;
  const side = radius * 2;

  // Dibujar fondo del icono (círculo o squircle con gradiente si aplica)
  let fillBg: string | CanvasGradient = spec.bg;
  if (spec.gradient) {
    const grad = ctx.createLinearGradient(x, y + side, x + side, y);
    grad.addColorStop(0, spec.gradient[0]);
    grad.addColorStop(0.5, spec.gradient[1]);
    grad.addColorStop(1, spec.gradient[2]);
    fillBg = grad;
  }

  ctx.fillStyle = fillBg;
  if (spec.shape === 'circle') {
    ctx.beginPath();
    ctx.arc(cx, cy, radius, 0, Math.PI * 2);
    ctx.fill();
  } else {
    drawRoundedPath(ctx, x, y, side, side, radius * 0.42);
    ctx.fill();
  }

  // Escalar el lienzo 24x24 oficial dentro del contenedor
  const padRatio = spec.viewBoxPaddingRatio ?? 0.18;
  const innerSize = side * (1 - padRatio * 2);
  const scale = innerSize / 24;
  const originX = cx - innerSize / 2;
  const originY = cy - innerSize / 2;

  ctx.translate(originX, originY);
  ctx.scale(scale, scale);

  for (const layer of spec.layers) {
    ctx.save();
    if (layer.dx || layer.dy) {
      ctx.translate(layer.dx || 0, layer.dy || 0);
    }
    if (layer.circle) {
      ctx.beginPath();
      ctx.arc(layer.circle.cx, layer.circle.cy, layer.circle.r, 0, Math.PI * 2);
      if (layer.fill) {
        ctx.fillStyle = layer.fill;
        ctx.fill();
      }
      if (layer.stroke) {
        ctx.strokeStyle = layer.stroke;
        ctx.lineWidth = layer.strokeWidth || 2;
        ctx.stroke();
      }
    } else if (layer.rect) {
      const rx = layer.rect.rx || 0;
      drawRoundedPath(ctx, layer.rect.x, layer.rect.y, layer.rect.w, layer.rect.h, rx);
      if (layer.fill) {
        ctx.fillStyle = layer.fill;
        ctx.fill();
      }
      if (layer.stroke) {
        ctx.strokeStyle = layer.stroke;
        ctx.lineWidth = layer.strokeWidth || 2;
        ctx.stroke();
      }
    } else if (layer.d && typeof Path2D !== 'undefined') {
      const path = new Path2D(layer.d);
      if (layer.fill) {
        ctx.fillStyle = layer.fill;
        ctx.fill(path, 'evenodd');
      }
      if (layer.stroke) {
        ctx.strokeStyle = layer.stroke;
        ctx.lineWidth = layer.strokeWidth || 2;
        ctx.lineCap = 'round';
        ctx.lineJoin = 'round';
        ctx.stroke(path);
      }
    }
    ctx.restore();
  }

  ctx.restore();
  return true;
}

export function renderBrandLogoSVGMarkup(
  logoType: QROptionLogo,
  cx: number,
  cy: number,
  size: number
): string {
  const spec = BRAND_LOGOS[logoType];
  if (!spec || logoType === 'none') return '';

  const radius = size * 0.45;
  const x = cx - radius;
  const y = cy - radius;
  const side = radius * 2;
  const padRatio = spec.viewBoxPaddingRatio ?? 0.18;
  const innerSize = side * (1 - padRatio * 2);
  const scale = innerSize / 24;
  const originX = cx - innerSize / 2;
  const originY = cy - innerSize / 2;

  const gradDef = spec.gradient
    ? `<defs><linearGradient id="qr-ig-grad" x1="0%" y1="100%" x2="100%" y2="0%"><stop offset="0%" stop-color="${spec.gradient[0]}"/><stop offset="50%" stop-color="${spec.gradient[1]}"/><stop offset="100%" stop-color="${spec.gradient[2]}"/></linearGradient></defs>`
    : '';
  const bgFill = spec.gradient ? 'url(#qr-ig-grad)' : spec.bg;
  const bgShape =
    spec.shape === 'circle'
      ? `<circle cx="${cx}" cy="${cy}" r="${radius}" fill="${bgFill}"/>`
      : `<rect x="${x}" y="${y}" width="${side}" height="${side}" rx="${radius * 0.42}" fill="${bgFill}"/>`;

  const layerSvg = spec.layers
    .map((layer) => {
      const tr = layer.dx || layer.dy ? ` transform="translate(${layer.dx || 0} ${layer.dy || 0})"` : '';
      const fillAttr = layer.fill ? ` fill="${layer.fill}"` : ' fill="none"';
      const strokeAttr = layer.stroke
        ? ` stroke="${layer.stroke}" stroke-width="${layer.strokeWidth || 2}" stroke-linecap="round" stroke-linejoin="round"`
        : '';
      if (layer.circle) {
        return `<circle cx="${layer.circle.cx}" cy="${layer.circle.cy}" r="${layer.circle.r}"${fillAttr}${strokeAttr}${tr}/>`;
      }
      if (layer.rect) {
        return `<rect x="${layer.rect.x}" y="${layer.rect.y}" width="${layer.rect.w}" height="${layer.rect.h}" rx="${layer.rect.rx || 0}"${fillAttr}${strokeAttr}${tr}/>`;
      }
      if (layer.d) {
        return `<path d="${layer.d}" fill-rule="evenodd"${fillAttr}${strokeAttr}${tr}/>`;
      }
      return '';
    })
    .join('');

  return `${gradDef}${bgShape}<g transform="translate(${originX} ${originY}) scale(${scale})">${layerSvg}</g>`;
}

function drawRoundedPath(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number
) {
  let radius = r;
  if (w < 2 * radius) radius = w / 2;
  if (h < 2 * radius) radius = h / 2;
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.arcTo(x + w, y, x + w, y + h, radius);
  ctx.arcTo(x + w, y + h, x, y + h, radius);
  ctx.arcTo(x, y + h, x, y, radius);
  ctx.arcTo(x, y, x + w, y, radius);
  ctx.closePath();
}
