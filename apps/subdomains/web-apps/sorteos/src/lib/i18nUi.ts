export function getUiTranslation(lang: string, key: UiKey): string {
  const dict = UI_EXTRA_TRANSLATIONS[lang as LangCode];
  if (dict && dict[key]) return dict[key];
  return UI_ES[key] || key;
}

/**
 * Devuelve un Set con los textos ya traducidos de forma nativa para un idioma,
 * evitando llamadas innecesarias del traductor automático de DOM.
 */
export function getKnownTranslatedValues(lang: string): Set<string> {
  const set = new Set<string>();
  const dict = UI_EXTRA_TRANSLATIONS[lang as LangCode];
  if (dict) {
    for (const val of Object.values(dict)) {
      if (val) set.add(val.trim());
    }
  }
  return set;
}

